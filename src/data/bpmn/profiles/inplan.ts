// Профиль разбора модели In.Plan (process-map-70e.5).
//
// ЗАЧЕМ ОН ОТДЕЛЬНО. Всё в этом файле — знание про КОНКРЕТНУЮ модель, а не про
// формат BPMN: кодовая схема шагов, словарь ролей, синонимы модулей. Ядро
// адаптера ничего этого не знает и из чужого файла делает карту победнее, но
// без единой догадки.
//
// Прецедент прямой: `SYSTEM_ALIASES` и таблицы `OWNER_DECISION_*` в
// scripts/import-pptx.py собраны так же и по той же причине — доменные
// допущения должны быть перечислены в одном месте, где их видно и можно
// оспорить, а не размазаны по правилам разбора.
//
// РЕШЕНИЕ ВЛАДЕЛЬЦА от 05.09.2026: полный профиль разрешён. Без него карта
// теряет 30 названий групп, 30 исполнителей шагов и все стрелки обзора.
import type { BpmnProfile } from '../profile.ts';

/**
 * Ведущий код шага: `DP-030-010`, `PS-010`, `DM-02`.
 *
 * Замерено: код есть у 103 подписей из 304 на уровне карты. Из диапазона кодов
 * участников выводится подпись безымянной группы — все 49 групп модели
 * безымянны, `categoryValue` в файле нет вовсе.
 */
const CODE_PATTERN = /^[A-Z]{2,4}-\d{2,3}(-\d{2,3})?/;

/**
 * Короткие подписи, которые автор кладёт РЯДОМ с шагом, обозначая исполнителя.
 *
 * Список выписан из файла, а не придуман: 17 «Фоновый процесс», 5 «Demand
 * Planner», 3 «Sales», по одному «Product Manager», «DRM», «Trade Promo
 * Planner» — и 2 «Demand Plannier».
 *
 * ОПЕЧАТКА «Plannier» ВКЛЮЧЕНА НАМЕРЕННО. Карта обязана показывать то, что
 * написано в схеме, а не исправлять содержание за автором: молчаливая правка
 * означала бы, что карта и файл расходятся, и найти это расхождение было бы
 * нечем. Чинить надо исходник в Modeler.
 */
const ROLE_STICKERS = new Set([
  'Фоновый процесс',
  'Demand Planner',
  'Demand Plannier',
  'Sales',
  'Product Manager',
  'DRM',
  'Trade Promo Planner',
]);

/**
 * Насколько близко наклейка должна лежать к узлу, чтобы считаться его.
 *
 * Замер по файлу: наклейки роли стоят в 59–66 px от центра единственного
 * соседнего узла. 120 — вдвое больше наблюдаемого, то есть запас есть, но
 * наклейка с другого конца диаграммы к узлу не прилипнет.
 */
const STICKER_DISTANCE = 120;

/**
 * Токен в имени граничного события → код модуля, на который оно указывает.
 *
 * Единственный источник стрелок обзора: связей между модулями в файле НЕТ
 * ВОВСЕ — у процесса верхнего уровня 12 подпроцессов и ни одного sequenceFlow.
 * Зато стартовые и конечные события внутри модулей названы кодами соседей:
 * SNP начинается с «DP: Планирование спроса», SOP заканчивается «SNP».
 */
const MODULE_ALIASES = new Map<string, string>([
  ['DP', 'DP'],
  ['SNP', 'SNP'],
  ['SP', 'SNP'],
  ['SOP', 'SOP'],
  ['S&OP', 'SOP'],
  ['TPP', 'TPP'],
  ['PS', 'PS'],
  ['MRP', 'MRP'],
  ['IO', 'IO'],
  ['DM', 'DM'],
]);

export const INPLAN_PROFILE: BpmnProfile = {
  processId: 'Process_Model_L0',
  codePattern: CODE_PATTERN,
  roleStickers: ROLE_STICKERS,
  stickerDistance: STICKER_DISTANCE,
  moduleAliases: MODULE_ALIASES,
};

/**
 * Профиль по id процесса.
 *
 * Включение по id, а не по флагу в интерфейсе: пользователю нечего решать, а
 * проверить одну строку в файле проще, чем объяснять, зачем нужен переключатель.
 */
export function profileFor(processId: string | null): BpmnProfile | undefined {
  return processId === INPLAN_PROFILE.processId ? INPLAN_PROFILE : undefined;
}
