// Доменный профиль разбора (process-map-70e.5).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. Три вещи в карте владельца выводятся не из формата
// BPMN, а из знания про In.Plan: кодовая схема шагов `XX-NNN-NNN`, синонимы
// модулей (`SP` это SNP, `S&OP` это SOP) и словарь ролей-наклеек. Чужой файл
// ничего этого не имеет.
//
// Поэтому ядро адаптера профиля НЕ ЗНАЕТ: из любого валидного BPMN оно делает
// валидную карту, просто более бедную. Домен собран в одном объявленном месте
// и включается по совпадению id процесса — прецедент прямой: `SYSTEM_ALIASES` и
// таблицы `OWNER_DECISION_*` в scripts/import-pptx.py собраны там ровно так же
// и по той же причине.

export interface BpmnProfile {
  /** По какому id процесса профиль включается. */
  readonly processId: string;
  /**
   * Ведущий код шага: `DP-030-010 Фоновая загрузка` → `DP-030-010`.
   * Из диапазона кодов участников выводится подпись безымянной группы.
   */
  readonly codePattern: RegExp;
  /**
   * Короткие подписи-наклейки, означающие исполнителя шага, а не описание.
   * В модели владельца это «Фоновый процесс», «Demand Planner» и подобные:
   * они лежат рядом с узлом, но не привязаны к нему ассоциацией.
   */
  readonly roleStickers: ReadonlySet<string>;
  /** Максимальное расстояние между центрами, на котором наклейка считается «своей». */
  readonly stickerDistance: number;
  /**
   * Токен в имени граничного события → код модуля, на который он указывает.
   * Единственный источник стрелок обзора: связей между модулями в файле нет.
   */
  readonly moduleAliases: ReadonlyMap<string, string>;
}

/** Профиль по умолчанию: ничего доменного не знает и ничего не выводит. */
export const NEUTRAL_PROFILE: BpmnProfile = {
  processId: '',
  // Заведомо не совпадающий шаблон: без профиля коды не выводятся вовсе.
  codePattern: /(?!)/,
  roleStickers: new Set<string>(),
  stickerDistance: 0,
  moduleAliases: new Map<string, string>(),
};
