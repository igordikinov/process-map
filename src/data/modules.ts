// Сколько у карты уровней и что показывает каждый (эпик M8, задача
// process-map-9mn.10).
//
// НЕ ПУТАТЬ С src/data/bpmn/modules.ts. Тот файл про подпроцессы загруженного
// BPMN-документа (какие элементы Camunda становятся этапами при разборе), этот
// — про уровень 1 готовой карты (какие этапы принадлежат модулю). Общее у них
// только слово.
//
// ЕДИНСТВЕННЫЙ ОТВЕТ на вопрос «сколько у карты уровней» даёт hasModules().
// Число уровней — свойство ДОКУМЕНТА, ровно как id и moduleLabel (SPEC §3,
// комментарий к ProcessMapSchema.modules). Запрещённые способы ответить на тот
// же вопрос, перечисленные поимённо, чтобы их нельзя было завести по
// невнимательности:
//   - map.id === '...' — карта с модулями появится не одна, и очередной id
//     пришлось бы дописывать в условие, которого никто не найдёт;
//   - флаг сборки (переменная MAP из scripts/mapTarget.ts или константа,
//     заведённая ради этого через define в vite.config.ts) — карту приносит не
//     только сборка: одна сборка несёт две версии карты (src/data/versions.ts),
//     а импорт BPMN подменяет её целиком (src/data/mapSwitch.ts), и флаг
//     продолжал бы описывать файл, которого на экране уже нет;
//   - import.meta.env — тот же снимок сборки, только прочитанный другим путём.
// Флаг сборки и import.meta.env отвечают на вопрос «что собрано», map.id — на
// вопрос «какая это карта». На заданный вопрос — «какой формы этот документ» —
// не отвечает ни один из трёх.
//
// ПОЧЕМУ УРОВЕНЬ ПРИХОДИТ СТРУКТУРОЙ (LevelState), А НЕ ТИПОМ ИЗ STORE. Store
// намеренно НЕ ЗНАЕТ КАРТУ — шапка src/store/useProcessStore.ts: «два источника
// истины (loader + store) неизбежно разъезжались бы». Эти функции карту знают,
// значит зависимость может идти только в одну сторону: данные ничего не знают о
// состоянии интерфейса, а экран приносит сюда два скаляра сам. Поля LevelState
// названы дословно как поля store, поэтому currentScreen(map,
// useProcessStore.getState()) компилируется без адаптера: currentModuleId
// store получил в задаче process-map-9mn.12, рядом с прежним currentStageId.
//
// МАССИВЫ НА ВЫХОДЕ — readonly, И ЭТО НЕ УКРАШЕНИЕ. Без фильтра (moduleId ===
// null, двухуровневая карта) функции отдают map.stages и map.overviewEdges ТОЙ
// ЖЕ ССЫЛКОЙ — то есть массивы самого документа, общего для всех экранов.
// sort() или push() в потребителе портили бы карту целиком, и порча вылезла бы
// на другом экране, далеко от причины. readonly делает такую правку ошибкой
// компиляции.
//
// Потребитель, чей вход сегодня объявлен как Stage[] (так устроен проп stages
// у Breadcrumbs), РАСШИРЯЕТ СВОЙ ВХОД до readonly Stage[], а не приводит
// результат через `as Stage[]`. Приведение выключило бы ровно ту проверку,
// ради которой readonly здесь стоит, и выключило бы молча: tsc промолчит и
// тогда, когда потребитель начнёт мутировать вход. Расширение же бесплатно —
// функция, которая массив только читает, принимает readonly без единой правки
// тела. buildOverviewGraph сегодня принимает карту целиком, и расширять ему
// нечего; новый вход «вид уровня 2», который заводит задача process-map-9mn.17
// ({stages, overviewEdges, frameLabel}), объявляется readonly СРАЗУ — иначе
// первый же вызов с результатом этих функций потребует того самого
// приведения.
//
// КЕША И МЕМОИЗАЦИИ ЗДЕСЬ НЕТ НАМЕРЕННО — запись для того, кто захочет добавить
// их «для симметрии». Известный модуль получает НОВЫЙ массив на каждый вызов.
// Стабильность ссылки — забота вызывающего: он зовёт функцию ВНУТРИ useMemo с
// зависимостями [map, moduleId], а не кладёт её результат в зависимости (новый
// массив пересобирал бы граф на каждый рендер). Пять модулей и двадцать этапов
// — линейный поиск дешевле инвалидации. Кеш был бы вторым местом, где живёт
// ответ, и ему пришлось бы узнавать о каждой подмене карты: импорт BPMN,
// правка ссылки в редакторе, переключение версии. useMemo у вызывающего узнаёт
// о них бесплатно — map у него уже в зависимостях. Прецедент кеша в
// src/data/versions.ts этому не противоречит: там кешируется разбор zod по 454
// узлам, здесь предмета для кеша нет.
//
// Из ./schema берутся ТОЛЬКО ТИПЫ (import type): в собранном JS у этого файла
// не остаётся ни одного импорта. Он ничего не исполняет при загрузке и ни на
// что не подписан — чистые функции над документом, который ему дали.
import type { Edge, Module, ProcessMap, Stage } from './schema';

/**
 * Карта, про которую УЖЕ ИЗВЕСТНО, что модули у неё есть.
 *
 * Существует ради сужения в hasModules(): в схеме поле необязательное, и без
 * предиката каждый потребитель уровня 1 писал бы map.modules! — по
 * восклицательному знаку на обращение, и ни один из них не был бы проверен
 * ничем, кроме внимательности автора.
 */
export type MapWithModules = ProcessMap & { modules: Module[] };

/**
 * Какой экран адресует текущее состояние.
 *
 * ИМЕННО MapScreen, А НЕ Screen. Screen — глобальный тип DOM (window.screen), и
 * забытый импорт не дал бы привычного «Cannot find name 'Screen'»: tsc молча
 * взял бы глобальный тип и жаловался бы на сами значения — «Type 'string' is
 * not assignable to type 'Screen'» у присваивания, «is not comparable» у
 * case. Ошибка есть, но указывает на значения, которые верны, а не на
 * пропущенный импорт (проверено tsc на этом проекте: lib DOM в tsconfig.json).
 * Плюс слово «экран» в этом проекте уже занято ссылкой на экран In.Plan
 * (ScreenLink в schema.ts), и второе значение того же слова читалось бы как
 * ошибка.
 *
 * Значения названы по СОДЕРЖИМОМУ экрана, а не по номеру уровня: на
 * двухуровневой карте 'stages' — это корень, на трёхуровневой — второй экран, и
 * имя 'level1' было бы неверным ровно в одном из двух случаев.
 */
export type MapScreen = 'modules' | 'stages' | 'steps';

/**
 * Часть состояния store, от которой зависит уровень.
 *
 * Интерфейс, а не два аргумента: вызов currentScreen(map, moduleId, stageId) с
 * двумя строками подряд молча пережил бы перестановку аргументов.
 */
export interface LevelState {
  readonly currentModuleId: string | null;
  readonly currentStageId: string | null;
}

/**
 * Трёхуровневая ли карта.
 *
 * ПРЕДИКАТ-СУЖЕНИЕ, а не boolean: после проверки map.modules становится
 * Module[] без восклицательного знака у каждого потребителя (см.
 * MapWithModules).
 *
 * ДЛИНА ПРОВЕРЯЕТСЯ, а не только наличие поля. Схема пустой список запрещает
 * (.min(1).optional(): «модулей нет» выражается отсутствием поля, и двух
 * способов сказать одно и то же у документа нет), но ТИП ProcessMap разрешает —
 * а карты собираются в коде руками, до и помимо разбора схемой: черновик в
 * src/data/bpmn/adapter.ts, фикстуры тестов. Предикат обязан быть верным для
 * значения этого типа, а не для тех значений, которые он получал до сих пор.
 *
 * ОДИН МОДУЛЬ — ТРЁХУРОВНЕВАЯ КАРТА: уровень 1 с единственной карточкой.
 * Пропускать его («модуль один — сразу покажем его этапы») нельзя: документ
 * терял бы и обретал целый экран от добавления второго модуля, а вместе с ним
 * менялись бы крошки, «Назад» и смысл ?module= в разосланных ссылках.
 *
 * Наличие moduleEdges признаком НЕ является: связи уровня 1 необязательны сами
 * по себе — карта из одного модуля рисует одну карточку и ни одного ребра.
 */
export function hasModules(map: ProcessMap): map is MapWithModules {
  return map.modules !== undefined && map.modules.length > 0;
}

/**
 * Модуль по id.
 *
 * ЕДИНСТВЕННЫЙ ПРИЗНАК «МОДУЛЬ НЕ НАЙДЕН» — moduleById(map, id) === undefined.
 * Не пустой результат stagesOfModule или overviewEdgesOf: пустым он бывает и у
 * существующего модуля (висящие stageIds — ошибка данных, которую ловит
 * validateIntegrity), и такой модуль надо чинить в данных, а не выбрасывать
 * пользователя на корень. На этом признаке стоит вторая защита экрана уровня 2
 * (задача process-map-9mn.16, эффект «модуль не найден → resetLevel()»,
 * дословно как useEffect в StageDetail.tsx).
 *
 * Возвращает undefined в трёх случаях: карта двухуровневая, moduleId === null
 * (уровень 1, ни один модуль не выбран), модуля с таким id в документе нет.
 * «Не найден» в смысле той защиты — только третий. На экране 'stages'
 * трёхуровневой карты второго случая не бывает (при null currentScreen отдаёт
 * 'modules', и экран этапов не смонтирован), а первый вызывающий отсекает
 * через hasModules(map), если на двухуровневой карте ему есть что защищать.
 */
export function moduleById(map: ProcessMap, moduleId: string | null): Module | undefined {
  if (moduleId === null || !hasModules(map)) {
    return undefined;
  }
  return map.modules.find((module) => module.id === moduleId);
}

/**
 * Модуль, которому принадлежит этап.
 *
 * НЕ ЗАМЕНЯЕТСЯ на moduleById(map, currentModuleId). У navigateToStage второй
 * аргумент необязателен (задача process-map-9mn.12: store не знает карту и
 * искать владельца этапа внутри себя не может), значит состояние «этап задан,
 * модуль не задан» законно и достижимо — например, из deep-link ?stage=7 без
 * ?module=. На уровне 3 модуль берётся ОТСЮДА, из документа, а не из store:
 * документ знает владельца всегда, store — только если ему сказали.
 *
 * Владелец ищется по module.stageIds — по тому, что документ ОБЪЯВЛЯЕТ, а не
 * по соседству номеров. Непрерывность номеров модуля — инвариант, который
 * введёт в validateIntegrity задача process-map-9mn.32, а не источник ответа:
 * выводить владельца из диапазона номеров значило бы опереться на проверку,
 * сделанную в другом месте, там, где ответ можно прочитать прямо. ЧЕСТНО: до
 * тех пор ни один тест не отличает moduleOfStage «по диапазону номеров» от
 * этой. На всех картах, где её проверяют, составы модулей — сплошные блоки
 * номеров, и оба способа дают один ответ (проверено мутантом, находящим
 * модуль по min..max номеров его этапов).
 *
 * Этап, заявленный двумя модулями, — ошибка данных, её ловит validateIntegrity
 * поимённо («заявлен сразу двумя модулями»). Какой из двух вернётся здесь,
 * контрактом НЕ является и тестом не закреплено: закреплять поведение на
 * документе, который проект считает битым, значило бы узаконить случайность
 * реализации.
 */
export function moduleOfStage(map: ProcessMap, stageId: string): Module | undefined {
  if (!hasModules(map)) {
    return undefined;
  }
  return map.modules.find((module) => module.stageIds.includes(stageId));
}

/**
 * Этапы, которые показывает уровень 2.
 *
 * ТРИ ВЕТКИ, и у каждой свой ответ:
 *   - moduleId === null — ФИЛЬТРА НЕТ: map.stages той же ссылкой, на карте
 *     ЛЮБОЙ формы;
 *   - двухуровневая карта — moduleId НЕ УЧИТЫВАЕТСЯ ВОВСЕ: map.stages той же
 *     ссылкой при любом id, в том числе мусорном;
 *   - трёхуровневая карта и id — этапы этого модуля; у неизвестного id —
 *     пустой массив.
 *
 * null — «ФИЛЬТРА НЕТ», А НЕ «ПУСТО», одинаково на обеих формах документа
 * (решение задачи: «null → map.stages»). Будь иначе, один и тот же аргумент
 * значил бы противоположное в зависимости от формы карты, и вызывающему
 * пришлось бы сначала выяснять форму — то есть повторять знание, ради
 * сосредоточения которого этот файл заведён. Какой ЭКРАН рисовать при null,
 * решает не эта функция, а currentScreen: на трёхуровневой карте это
 * 'modules', и уровень 2 при нём не строится вовсе.
 *
 * НА ДВУХУРОВНЕВОЙ КАРТЕ КОРЕНЬ НЕ БЫВАЕТ ПУСТЫМ. Проверка hasModules стоит ДО
 * поиска модуля, и это не оптимизация: залипший от прошлой карты
 * currentModuleId (подмена карты, ?module= в адресе) иначе оставил бы обзор
 * двухуровневой карты пустым полотном — экран есть, карточек нет, и ни одного
 * признака причины.
 *
 * map.stages отдаётся ТОЙ ЖЕ ССЫЛКОЙ, а не копией: фильтра нет — копировать
 * нечего, и потребитель получает ровно тот массив, из которого Overview строит
 * граф сегодня. Портить его мешает readonly (шапка файла).
 *
 * ПОРЯДОК — ИЗ module.stageIds, а не из map.stages и не по stage.number. Индекс
 * в результате означает сразу две вещи: позицию карточки на полотне
 * (overviewGraph.ts, positionOf(index)) и k в бейдже «Этап k из n» (задача
 * process-map-9mn.17, module.stageIds.indexOf(stage.id) + 1). У двух
 * потребителей одного порядка источник обязан быть один, иначе карточка и её
 * бейдж разойдутся, и оба экрана при этом будут выглядеть рабочими. Сортировка
 * по номеру была бы молчаливой починкой данных: инвариант, который готовит
 * задача process-map-9mn.32 (решение 9mn.24, вариант «а»), требует
 * непрерывности МНОЖЕСТВА номеров модуля, а объявленный порядок stageIds
 * оставляет авторитетом.
 *
 * Этап ищется по id, а не по номеру, извлечённому из id: номер в id бывает
 * (stage-3 в фикстуре, stage-1-dp в inplan-model), но это совпадение формы, а
 * не контракт — схема id этапа не разбирает.
 *
 * ПУСТОЙ РЕЗУЛЬТАТ — СЛЕДСТВИЕ, А НЕ СИГНАЛ. Признак «модуль не найден» —
 * только moduleById(map, id) === undefined (см. там же): пустым бывает и
 * результат существующего модуля, все stageIds которого висят. Этап, которого
 * нет в документе, из результата выпадает, а не доезжает до экрана как
 * undefined (висящий stageIds ловит validateIntegrity). Оба поведения на битых
 * данных закреплены тестами на карте, собранной мимо схемы
 * (tests/modules.test.ts, danglingStagesMap).
 *
 * Известный модуль — новый массив на каждый вызов; почему кеша нет и как
 * вызывать из компонента — шапка файла.
 */
export function stagesOfModule(map: ProcessMap, moduleId: string | null): readonly Stage[] {
  if (moduleId === null || !hasModules(map)) {
    return map.stages;
  }
  const module = moduleById(map, moduleId);
  if (module === undefined) {
    return [];
  }
  // Локальное имя byId, а не stageById: stageById зарезервировано за общей
  // функцией «найти этап по id» (задача process-map-q8d), и одноимённый
  // локальный помощник здесь путал бы поиск по проекту.
  const byId = new Map(map.stages.map((stage) => [stage.id, stage]));
  return module.stageIds
    .map((stageId) => byId.get(stageId))
    .filter((stage): stage is Stage => stage !== undefined);
}

/**
 * Рёбра, которые показывает уровень 2: всё, что КАСАЕТСЯ этапов модуля.
 *
 * Ветки те же, что у stagesOfModule, и по тем же доводам: moduleId === null —
 * фильтра нет, map.overviewEdges той же ссылкой на карте любой формы;
 * двухуровневая карта — moduleId не учитывается вовсе, map.overviewEdges той
 * же ссылкой при любом id; трёхуровневая и неизвестный id — пустой массив,
 * который, как и там, сигналом «модуль не найден» НЕ является (сигнал — только
 * moduleById(map, id) === undefined).
 *
 * КАСАЕТСЯ, А НЕ «ОБА КОНЦА ВНУТРИ». Обзорные рёбра бывают трёх видов: этап →
 * этап (оба конца всегда в одном модуле — кросс-модульное ребро запрещено
 * validateIntegrity), система → этап и этап → система. Система ничьему модулю
 * не принадлежит, поэтому правило «оба конца в модуле» выбросило бы с экрана
 * ВСЕ интеграционные рёбра сразу.
 *
 * ОБА КОНЦА ПРОВЕРЯЮТСЯ ОТДЕЛЬНО, и это не симметрия ради симметрии: система
 * стоит и источником (ERP → «Проверка ограничений»), и приёмником («План
 * поставок» → PS). Проверка одного только source выглядит работающей — она
 * оставляет исходящие стрелки на месте, — а входящая стрелка от системы просто
 * пропадает с экрана модуля. Проверка одного только target — зеркально теряет
 * исходящие.
 *
 * ЧЕГО ЭТО ПРАВИЛО НЕ РАЗЛИЧАЕТ, честно: «взять касающиеся СВОИХ этапов» и
 * «отбросить касающиеся ЧУЖИХ» расходятся ровно на ребре, у которого ни один
 * конец не является этапом («система → система»). Схема такое ребро сегодня
 * пропускает, но на уровне 2 оно не соединяет ничего из нарисованного —
 * семантический мусор, и закреплять на нём поведение незачем. Запрет на него
 * вводит в validateIntegrity задача process-map-9mn.32 (пункт
 * process-map-9ow).
 *
 * Известный модуль — новый массив на каждый вызов, кеша нет (шапка файла).
 */
export function overviewEdgesOf(map: ProcessMap, moduleId: string | null): readonly Edge[] {
  if (moduleId === null || !hasModules(map)) {
    return map.overviewEdges;
  }
  const module = moduleById(map, moduleId);
  if (module === undefined) {
    return [];
  }
  const own = new Set(module.stageIds);
  return map.overviewEdges.filter((edge) => own.has(edge.source) || own.has(edge.target));
}

/**
 * Какой экран показывать при таком состоянии.
 *
 * ОСТОРОЖНО, ЦИКЛ РЕНДЕРА. В проекте zustand v5, и все обращения к store —
 * селекторы на ОДИН СКАЛЯР. Форма LevelState буквально приглашает собрать
 * объект внутри селектора, а селектор, возвращающий новый объект, даёт здесь не
 * лишний ререндер, а цикл useSyncExternalStore («The result of getSnapshot
 * should be cached» → «Maximum update depth exceeded»). Правильный вызов:
 *
 *     const currentModuleId = useProcessStore((s) => s.currentModuleId);
 *     const currentStageId = useProcessStore((s) => s.currentStageId);
 *     const screen = currentScreen(map, { currentModuleId, currentStageId });
 *
 * Объект собирается В КОМПОНЕНТЕ, после двух селекторов, и store о нём не
 * знает.
 *
 * ПОРЯДОК ПРОВЕРОК: этап старше модуля. Состояние «этап задан, модуль не задан»
 * законно (см. moduleOfStage), и на нём экран обязан быть уровня 3, а не
 * уровня 1 — иначе deep-link ?stage=7 без ?module= открывал бы не то, что
 * просили.
 *
 * СУЩЕСТВОВАНИЕ модуля и этапа НЕ ПРОВЕРЯЕТСЯ намеренно: функция отвечает на
 * вопрос «какой уровень адресует состояние», а не «валидно ли оно». Так же
 * устроен сегодняшний App.tsx (currentStageId === null ? обзор : детализация),
 * и возврат из тупика живёт эффектом в самом экране (StageDetail.tsx: этап не
 * найден → resetLevel()). Проверяй мы существование здесь, тупик чинился бы во
 * время рендера — то есть сменой состояния во время рендера, на что React
 * ругается.
 */
export function currentScreen(map: ProcessMap, level: LevelState): MapScreen {
  if (level.currentStageId !== null) {
    return 'steps';
  }
  // Посторонний currentModuleId на ДВУХУРОВНЕВОЙ карте (?module=dp в адресе,
  // залипшее значение после подмены карты) экрана модулей не создаёт: экрана
  // уровня 1 у такого документа нет вовсе.
  if (level.currentModuleId !== null || !hasModules(map)) {
    return 'stages';
  }
  return 'modules';
}
