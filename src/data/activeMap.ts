// Какая карта показывается сейчас (process-map-70e.8).
//
// МОДУЛЬ НАМЕРЕННО БЕЗ ЗАВИСИМОСТЕЙ, кроме типа. Встроенную карту знает
// loader.ts, а он импортирует этот модуль — если бы и этот знал про loader,
// получилось бы кольцо. Поэтому здесь живёт РОВНО ОДНА вещь: загруженная
// пользователем карта, если она есть. Кто её показывает и как — решает loader.
//
// ПОЧЕМУ ОНА ЖИВЁТ СЕССИЮ, А НЕ В localStorage.
//
// Прецедент — `mode` из SPEC §4.4: режим редактора намеренно не персистится,
// «иначе он залипал бы у читателя вики». Залипшая чужая карта хуже залипшего
// режима: читатель откроет страницу вики и увидит НЕ ТОТ процесс, который эта
// страница описывает, и ни одного признака подмены на экране не будет.
//
// Место не аргумент: `src/data/snp/process.json` весит 69 KB при лимите
// хранилища в мегабайты. Дело не в объёме, а в том, что состояние приложения
// не должно переживать перезагрузку молча.
//
// Путь «сохранить надолго» у пользователя есть и он лучше: «Экспорт JSON» →
// файл в репозиторий → карта становится встроенной.
import type { ProcessMap } from './schema';

let imported: ProcessMap | null = null;

/** Показать загруженную карту вместо встроенной. */
export function setImportedMap(map: ProcessMap): void {
  imported = map;
}

/** Вернуться к встроенной карте. */
export function clearImportedMap(): void {
  imported = null;
}

/** Загруженная карта или `null`, если показывается встроенная. */
export function getImportedMap(): ProcessMap | null {
  return imported;
}

/**
 * Показывается ли сейчас загруженная карта.
 *
 * Нужно интерфейсу: заголовок сменился бы и при переходе на вторую встроенную
 * карту, поэтому признаком подмены он служить не может — нужен явный.
 */
export function isImportedActive(): boolean {
  return imported !== null;
}
