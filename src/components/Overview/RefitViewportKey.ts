// Ключ пересчёта вида для RefitViewport (задача process-map-9mn.19).
//
// Отдельным модулем, а не в RefitViewport.tsx: файл компонента, экспортирующий
// ещё и функцию, ломал бы Fast Refresh (react-refresh/only-export-components в
// eslint.config.js). Ключ собирают оба экрана с RefitViewport — экран модулей
// (ModulesOverview.tsx) и экран этапов (Overview.tsx), — и формат ключа обязан
// быть у них один: общая функция, а не два шаблона строки.
import type { MapScreen } from '../../data/modules';

/**
 * Из чего состоит ключ пересчёта вида (process-map-9mn.19).
 *
 * Все четыре поля ОБЯЗАТЕЛЬНЫ, модуль — тоже, хотя бывает null: экран, который
 * забыл бы передать модуль, не компилируется, а не подгоняет вид реже, чем
 * нужно.
 */
export interface FitKeyParts {
  /**
   * Экран, чей это вид. Прежний ключ `compact + map.id` экранов не различал:
   * уровни 1 и 2 трёхуровневой карты — обзоры одной и той же карты в одном
   * режиме, и отличал их только модуль в ключе экрана этапов
   * (process-map-9mn.17). А модуль там на мгновение бывает undefined —
   * модуль не найден, и App ещё не вернул читателя на корень (Overview.tsx),
   * — и тогда ключи двух экранов совпадали дословно.
   *
   * Сегодня переход между уровнями всё равно подгоняет вид, потому что экраны
   * — разные компоненты и RefitViewport монтируется заново. Но это заслуга
   * устройства App, а не ключа: сведи экраны в общую оболочку с одним
   * полотном — и переход молча перестал бы подгонять вид.
   */
  readonly screen: MapScreen;
  readonly compact: boolean;
  readonly mapId: string;
  /**
   * Модуль, этапы которого на экране; null — экран не про один модуль
   * (уровень 1 трёхуровневой карты, обзор двухуровневой). Два модуля на
   * уровне 2 — два разных полотна: число этапов у модулей разное, и вид,
   * подогнанный под первый, резал бы или сжимал второй. Экран этапов при этом
   * законно остаётся смонтированным (тот же компонент Overview, другие пропы),
   * и тогда подгонку даёт только ключ.
   */
  readonly moduleId: string | null;
}

/**
 * Ключ RefitViewport. JSON-кортеж, а не склейка через двоеточие: id карты и
 * модуля — данные документа, и двоеточие в одном из них склеило бы два разных
 * набора частей в одну строку.
 */
export function fitKeyOf({ screen, compact, mapId, moduleId }: FitKeyParts): string {
  return JSON.stringify([screen, compact, mapId, moduleId]);
}
