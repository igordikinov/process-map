// Уместился ли текст элемента под клампом строк (process-map-9mn.37).
//
// ЗАЧЕМ ИЗМЕРЕНИЕ, А НЕ ПРАВИЛО ПО ДЛИНЕ. Кламп заголовка панели
// (-webkit-line-clamp: 2, NodeDrawer.module.css .title) режет по ширине
// строки, а не по числу символов: сколько букв влезает в две строки, решают
// шрифт, начертание и ширина панели. Порог «N символов» в коде разошёлся бы с
// любым из них молча — и первым же длинным абзацем вернул бы дефект, ради
// которого хук заведён: текст подробности, видимый только наполовину. Спросить
// у самой вёрстки — единственный ответ, который не врёт.
//
// КАК. Под клампом высота блока ограничена двумя строками, а содержимое
// раскладывается целиком и выходит за блок: scrollHeight — высота всего
// текста, clientHeight — видимой части. Совпали — срезано ничего не было.
//
// СОМНЕНИЕ — В ПОЛЬЗУ «СРЕЗАНО». Хук отвечает true, только когда вёрстка
// ДОКАЗАЛА, что текст виден целиком. Нет раскладки (jsdom: обе высоты — нули),
// элемент скрыт, ещё не измерено — ответ false. Вызывающий код по false
// показывает полный текст ещё раз, в теле панели: лишний повтор короткой
// строки дешевле, чем молча потерянный хвост абзаца.
import { useLayoutEffect, useState, type RefObject } from 'react';

/**
 * true — текст элемента `ref` виден целиком, кламп ничего не срезал.
 * false — срезал, либо измерить не удалось (см. шапку файла).
 *
 * `enabled: false` — не измерять вовсе (ответ false): панели шага, данных и
 * прочих узлов измерение не нужно, и их DOM и рендеры не меняются.
 * `text` — текст элемента: при его смене вёрстка измеряется заново.
 */
export function useFitsWithoutClamp(
  ref: RefObject<HTMLElement>,
  enabled: boolean,
  text: string,
): boolean {
  const [fits, setFits] = useState(false);

  // useLayoutEffect, а не useEffect: измерение и его последствие (скрыть
  // повтор в теле панели) успевают до первой отрисовки — без мигания текста.
  useLayoutEffect(() => {
    const element = ref.current;
    if (!enabled || element === null) {
      return;
    }
    const measure = (): void => {
      setFits(element.clientHeight > 0 && element.scrollHeight <= element.clientHeight);
    };
    measure();

    // Шрифты подключены с font-display: swap (theme/fonts.css): пока Open Sans
    // грузится, текст свёрстан запасным шрифтом, и первое измерение относится
    // к нему. Панель, открытая сразу по deep-link (?node=…, SPEC §4.7), —
    // ровно этот случай: после подмены шрифта абзац, уместившийся в две
    // строки, может перестать умещаться. Поэтому по готовности шрифтов —
    // измерение заново. В jsdom document.fonts нет, отсюда ?. — тип DOM
    // считает поле обязательным.
    let active = true;
    void document.fonts?.ready.then(() => {
      if (active) {
        measure();
      }
    });
    return () => {
      active = false;
    };
  }, [ref, enabled, text]);

  return enabled && fits;
}
