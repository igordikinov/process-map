// Форматирование значений для шапки (src/utils/format.ts).
//
// Файл заведён задачей process-map-vjz.10. До неё formatIsoDate не был закреплён
// НИЧЕМ, кроме одной строки в tests/overview.test.tsx, где ожидалась готовая
// подпись «Обновлено 24.08.2026». Как только дата карты перестала быть вечной,
// ту строку пришлось заменить вычислением из данных — и без этого файла проект
// остался бы вообще без проверки того, что дата рисуется как DD.MM.YYYY.
import { describe, expect, it } from 'vitest';
import { formatIsoDate } from '../src/utils/format';

describe('formatIsoDate', () => {
  it('ISO-дата превращается в DD.MM.YYYY', () => {
    expect(formatIsoDate('2026-08-30')).toBe('30.08.2026');
  });

  it('день и месяц не меняются местами', () => {
    // Обязательный случай: в датах вида 30.08 перестановка видна сразу, а в
    // 2026-01-02 обе половины однозначны, и «02.01» против «01.02» —
    // единственное, что отличает правильный порядок от обратного.
    expect(formatIsoDate('2026-01-02')).toBe('02.01.2026');
  });

  it('хвост времени игнорируется', () => {
    expect(formatIsoDate('2026-08-30T16:43:56Z')).toBe('30.08.2026');
  });

  it('строка не в формате ISO отдаётся как есть', () => {
    // Намеренное поведение (см. комментарий в format.ts): показать сырое
    // значение лучше, чем «Invalid Date».
    expect(formatIsoDate('позавчера')).toBe('позавчера');
    expect(formatIsoDate('')).toBe('');
  });

  it('дата не съезжает в отрицательных часовых поясах', () => {
    // Ради этого дата разбирается регуляркой, а не new Date(): конструктор
    // трактует «2026-08-30» как UTC-полночь, и западнее Гринвича вышло бы 29-е.
    expect(formatIsoDate('2026-08-30')).toBe('30.08.2026');
  });
});
